"""

Desenvolva um algoritmo que escreva na tela os números de 10 até 0 (em ordem decrescente), utilizando obrigatoriamente o comando de repetição for.

"""

def main():
    
    for i in range(10, -1, -1):
        print(f'{i}')
    
    return 0
    
if __name__ == "__main__":
    main()